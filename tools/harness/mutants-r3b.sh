#!/usr/bin/env bash
# The R3b-1 mutant round — the ROW CYCLE: turn-taking between same-row resets, its guard, and its demand link.
#
# ⛔ FOR EVERY MUTANT, THE TWO QUESTIONS (V4's Part 5, kept):
#   1. CAN IT MOVE ITS ROW'S OWN REFERENCE? Every row in `loader/cycle.test.mjs` is judged against something the
#      LOADER cannot touch — the stub's own `canReset` flags, the act counts the stub records, the `player` the
#      stub owns — or against a CONTROL built in the same test (the demand row measures two builds against each
#      other, and the weights build is the reference). The cycle's own `cycleState()` is a readout of the thing
#      under test, so no row rests on it alone: every one of them also asserts an ACT COUNT or an ENGINE fact.
#   2. DOES A SECOND GUARD MAKE IT REDUNDANT? Named beside the ones where it does. A mutant that only changes a
#      LABEL is excluded on purpose: `waiting:turn` is asserted in the vocabulary table AND as a value on a real
#      decision, so dropping it reddens two rows and proves nothing about the mechanism.
#
# ⛔ RESTORED FROM A COPY, NEVER FROM GIT — a harness that restores with `git checkout` restores over uncommitted
# work. The script refuses to start on a dirty tree, because a dirty tree is the case where the copy is the only
# thing between the mutation and the work.
#
# ⛔ DO NOT EDIT THIS FILE WHILE IT IS RUNNING. Bash reads a script incrementally, by byte offset.
#
#   bash tools/harness/mutants-r3b.sh <out-dir> [name-filter]
set -uo pipefail
cd "$(dirname "$0")/../.."
OUT="${1:?usage: mutants-r3b.sh <out-dir> [name-filter]}"
ONLY="${2:-}"
mkdir -p "$OUT"
if [ -n "$(git status --porcelain)" ]; then echo "REFUSING: the tree is dirty. Commit first — a mutant round restores over whatever is here."; exit 1; fi
AUTO=loader/tmt-auto.js
cp "$AUTO" "$OUT/tmt-auto.js.orig"
restore() { cp "$OUT/tmt-auto.js.orig" "$AUTO"; }
trap restore EXIT

mutant() {
  local name="$1" mut="$2"; shift 2
  if [ -n "$ONLY" ] && [[ "$name" != *"$ONLY"* ]]; then return 0; fi
  restore
  python3 -c "$mut" || { echo "$name: THE MUTATION DID NOT APPLY"; return 1; }
  echo "=== $name ==="
  git --no-pager diff --stat -- "$AUTO"
  "$@" > "$OUT/$name.log" 2>&1
  echo "$name: exit $? — $(grep -cE '^(RED|not ok)' "$OUT/$name.log") RED row(s), $(grep -cE '^(GREEN|ok )' "$OUT/$name.log") green"
  grep -E '^(RED|not ok)' "$OUT/$name.log" | cut -c1-260
  restore
  git --no-pager diff --stat -- "$AUTO" | grep . && echo "!! NOT RESTORED" || echo "restored: diff is empty"
}

UNIT="node --test loader/cycle.test.mjs"
# ⛔ THE WHOLE-STRETCH RATIO ROW. Two defects of this slice are invisible to every stub leg (§34), so their mutants
# are driven by the gate that can see them. ONE run per cell: a mutant round asks whether a row RED-dens, and a
# twice-equal check is the row's own business when it runs for real.
RATIO="node tools/harness/gates-r3b.mjs --part 7 --no-summary --no-write --repeat7 1 --pool 2"

# ---- R1: the cycle binds EVERY member --------------------------------------------------------------------------
# ⛔ THE PLANNER'S OWN VOID CELL, AS A MUTATION. Three of its nine cells gated only `q`; the eager `reset:h` that was
# left out fired 44 times and wiped row 2 before `q`'s turn could be used. "Members are the carriers" is exactly
# that build.
