# ---- R4: the memory is the LOADER's own -------------------------------------------------------------------------
# ⛔ THE TRAP THE PLANNER'S SIX VOID CELLS FELL INTO, AS A MUTATION. `player[l].resetTime` exists ONLY on the
# 2.7-style engine; on the stub and on ptr it is `undefined`, so the typical is never a number and the guard never
