  "p='$AUTO';s=open(p).read();o='      by[key].members.push(g);\n      var m = turnMod(g);';assert o in s;s=s.replace(o,'      var m = turnMod(g);\n      if (m) by[key].members.push(g);');open(p,'w').write(s)" \
  $UNIT

# ⛔ AND THE OTHER HALF OF R1: a cycle keyed by the LAYER rather than by the ROW. Every member gets its own cycle,
# every member always holds its own turn, and nobody ever waits — a scheduler that schedules nothing, green in every
# hash and in every mark. No second guard sees it: the act counts are unchanged from the no-cycle control.
mutant m2-cycle-keyed-by-layer \
